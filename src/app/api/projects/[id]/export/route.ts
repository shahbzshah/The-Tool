import { NextResponse } from "next/server";
import { prisma } from "@/lib/db";
import JSZip from "jszip";
import { DOC_KINDS } from "@/lib/constants";
import { averageScore, parseJsonField, type IdeaScores } from "@/lib/constants";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

function slug(text: string): string {
  return (
    text
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 40) || "project"
  );
}

/**
 * GET /api/projects/[id]/export
 * One-click bundle for the whole project: ideas overview, stitch prompt,
 * and every document generated for approved ideas.
 */
export async function GET(
  _req: Request,
  { params }: { params: { id: string } }
) {
  try {
    const project = await prisma.project.findUnique({
      where: { id: params.id },
      include: {
        ideas: {
          orderBy: { createdAt: "asc" },
          include: { documents: true },
        },
        stitchPrompt: true,
      },
    });
    if (!project) {
      return NextResponse.json({ error: "Project not found." }, { status: 404 });
    }

    const zip = new JSZip();

    // IDEAS.md — overview of every idea with scores
    const ideaLines = project.ideas.map((idea, i) => {
      const scores = parseJsonField<IdeaScores>(idea.scores);
      const features = (() => {
        try {
          const arr = JSON.parse(idea.features);
          return Array.isArray(arr) ? arr.map(String) : [];
        } catch {
          return [];
        }
      })();
      return [
        `## ${i + 1}. ${idea.title}`,
        "",
        `**Status:** ${idea.status}${scores ? ` | **Score:** ${averageScore(scores)}/10 (novelty ${scores.novelty}, feasibility ${scores.feasibility}, demand ${scores.marketDemand})` : ""}`,
        "",
        idea.pitch,
        "",
        features.length ? `**Features:**\n${features.map((f) => `- ${f}`).join("\n")}` : "",
        `**Target audience:** ${idea.targetAudience}`,
        idea.monetization ? `**Monetization:** ${idea.monetization}` : "",
      ]
        .filter(Boolean)
        .join("\n");
    });

    zip.file(
      "IDEAS.md",
      [
        `# ${project.name}`,
        "",
        `**Category:** ${project.category}`,
        project.preferences ? `**Preferences:** ${project.preferences}` : "",
        `**Generated:** ${new Date(project.createdAt).toISOString().slice(0, 10)}`,
        "",
        "---",
        "",
        ...ideaLines,
      ]
        .filter(Boolean)
        .join("\n")
    );

    // Stitch prompt if generated
    if (project.stitchPrompt) {
      zip.file("stitch-prompt.md", project.stitchPrompt.promptText);
    }

    // All documents for approved ideas, grouped per idea
    for (const idea of project.ideas) {
      if (idea.status !== "approved" || idea.documents.length === 0) continue;
      const dir = `docs/${slug(idea.title)}`;
      for (const doc of idea.documents) {
        const label = DOC_KINDS.find((d) => d.kind === doc.kind)?.label ?? `${doc.kind}.md`;
        zip.file(`${dir}/${label}`, doc.content);
      }
    }

    const docCount = project.ideas.reduce(
      (sum, i) => sum + i.documents.length,
      0
    );

    zip.file(
      "README.md",
      [
        `# Export bundle — ${project.name}`,
        "",
        `Generated by Ideas App on ${new Date().toISOString().slice(0, 10)}.`,
        "",
        "## Contents",
        "- `IDEAS.md` — all generated ideas with AI scores",
        project.stitchPrompt ? "- `stitch-prompt.md` — the Google Stitch prompt for this project" : "",
        docCount > 0
          ? `- \`docs/<idea>/\` — full documentation sets (${docCount} documents across approved ideas)`
          : "- (No documents yet — approve an idea and generate docs to include them here)",
      ]
        .filter(Boolean)
        .join("\n")
    );

    const buffer = await zip.generateAsync({ type: "nodebuffer" });
    return new NextResponse(new Uint8Array(buffer), {
      status: 200,
      headers: {
        "Content-Type": "application/zip",
        "Content-Disposition": `attachment; filename="${slug(project.name)}-bundle.zip"`,
        "Content-Length": String(buffer.length),
      },
    });
  } catch (err) {
    console.error("Project export failed:", err);
    return NextResponse.json({ error: "Export failed." }, { status: 500 });
  }
}